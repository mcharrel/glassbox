import { parseDiffData } from '../../git/parseDiffData.js';
import type { NarrativeFileOrder, ReviewFile } from '../state.js';

const DEPENDENCY_FILES = /^(?:go\.(?:mod|sum|work(?:\.sum)?)|(?:package|package-lock|npm-shrinkwrap|composer)\.json|composer\.lock|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|pom\.xml|maven_install(?:_[\w-]+)?\.(?:bzl|json)|(?:go_)?deps\.bzl|dependencies\.bzl|repositories\.bzl|MODULE\.bazel(?:\.lock)?|WORKSPACE(?:\.bazel)?|build\.gradle(?:\.kts)?|gradle\.(?:properties|lockfile)|libs\.versions\.toml|Cargo\.(?:toml|lock)|requirements(?:[.-][\w-]+)?\.txt|Pipfile(?:\.lock)?|pyproject\.toml|poetry\.lock|uv\.lock|Gemfile(?:\.lock)?)$/i;

function priority(file: ReviewFile): number {
  const path = file.file_path.replaceAll('\\', '/');
  const name = path.split('/').at(-1) ?? path;
  // Generated protobufs take precedence over dependency and test directories.
  if (/\.pb(?:\.gw)?\.(?:go|cc|h|swift|dart)$|_pb2(?:_grpc)?\.py$|_pb(?:\.d)?\.(?:js|ts)$|_grpc_pb\.(?:js|ts)$|\.pb(?:enum|json|server)\.dart$/i.test(name)
    || /(?:^|\/)generated[-_]?(?:protos?|protobuf|grpc)(?:\/|$)/i.test(path)
    || generatedProtoHeader(file)) return 4;
  if (DEPENDENCY_FILES.test(name) || /(?:^|\/)vendor\//.test(path)) return 3;
  if (/(?:^|\/)(?:tests?|__tests__|testdata|testutils?)(?:\/|$)/i.test(path)
    || /[._](?:test|spec)\.(?:go|[cm]?[jt]sx?|py|java|kt|scala|rb|rs|cc|cpp|c|h)$/i.test(name)
    || /(?:Tests?|TestCase|IT)\.(?:java|kt|scala)$/.test(name)
    || /^test_[^.]+\.(?:py|cc|cpp)$/i.test(name)
    || /^Test[^.]+\.(?:java|kt|scala)$/.test(name)) return 2;
  if (/\.ya?ml$/i.test(name)) return 1;
  return 0;
}

function generatedProtoHeader(file: ReviewFile): boolean {
  if (!/\.(?:java|kt|go|py|cc|h|cs|js|ts|php|rb|swift|dart)$/i.test(file.file_path)
    || !/Generated by the protocol buffer compiler|Code generated by protoc/i.test(file.diff_data ?? '')) return false;
  const diff = parseDiffData(file.diff_data);
  return diff?.hunks.some(hunk => hunk.lines.some(line =>
    (line.newNum ?? line.oldNum ?? Infinity) <= 40
    && /^\s*(?:\/\/|#|\/\*|\*)\s*(?:Generated by the protocol buffer compiler|Code generated by protoc)/i.test(line.content),
  )) ?? false;
}

/** Highest-priority files first; source files retain Glassbox's narrative reading order. */
export function readingOrder(files: ReviewFile[], narrative: NarrativeFileOrder[] | null): ReviewFile[] {
  const positions = new Map<string, number>();
  for (const item of narrative ?? []) {
    if (Number.isFinite(item.position)) {
      positions.set(item.reviewFileId, Math.min(positions.get(item.reviewFileId) ?? Infinity, item.position));
    }
  }
  return files.map(file => ({ file, priority: priority(file), position: positions.get(file.id) ?? Infinity }))
    .sort((a, b) => a.priority - b.priority
      || (a.priority === 0 && a.position !== b.position ? a.position - b.position : 0)
      || a.file.file_path.localeCompare(b.file.file_path)
      || a.file.id.localeCompare(b.file.id))
    .map(item => item.file);
}
