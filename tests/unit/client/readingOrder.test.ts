import { describe, expect, it } from 'vitest';

import { readingOrder } from '../../../src/client/sidebar/readingOrder.js';
import type { NarrativeFileOrder, ReviewFile } from '../../../src/client/state.js';
import { unchangedFileDiff } from '../../../src/git/parseDiffData.js';

function file(path: string, content?: string): ReviewFile {
  return {
    id: path, file_path: path, review_id: 'review', status: 'pending', created_at: '',
    diff_data: content === undefined ? null : JSON.stringify(unchangedFileDiff(path, content)),
  };
}

function rank(path: string, position: number): NarrativeFileOrder {
  return { reviewFileId: path, filePath: path, position, rationale: '' };
}

function paths(files: ReviewFile[], narrative: NarrativeFileOrder[] | null = null): string[] {
  return readingOrder(files, narrative).map(item => item.file_path);
}

describe('personal reading order', () => {
  it('handles no files and a single unanalysed file without modifying inputs', () => {
    expect(readingOrder([], null)).toEqual([]);
    const files = [file('src/main.go')];
    expect(readingOrder(files, null)).toEqual(files);
    expect(readingOrder(files, null)).not.toBe(files);
  });

  it('groups source, YAML, tests, dependencies, generated protos; only source follows AI order', () => {
    const names = ['gen/service.pb.go', 'pnpm-lock.yaml', 'src/service_test.go', 'deploy.yaml', 'src/a.go', 'src/z.go'];
    const files = names.map(name => file(name));
    const analysis = names.map((name, i) => rank(name, i));
    analysis.find(item => item.filePath === 'src/z.go')!.position = -1;
    const expected = ['src/z.go', 'src/a.go', 'deploy.yaml', 'src/service_test.go', 'pnpm-lock.yaml', 'gen/service.pb.go'];
    expect(paths(files, analysis)).toEqual(expected);
    expect(paths([...files].reverse(), [...analysis].reverse())).toEqual(expected);
    expect(files.map(item => item.file_path)).toEqual(names);
  });

  it('keeps unscored source ahead of tests and ignores stale analysis ids', () => {
    const files = ['src/c.go', 'tests/a.go', 'src/a.go', 'src/b.go'].map(name => file(name));
    expect(paths(files, [rank('removed.go', 0), rank('tests/a.go', 1), rank('src/c.go', 2)]))
      .toEqual(['src/c.go', 'src/a.go', 'src/b.go', 'tests/a.go']);
    expect(paths(files)).toEqual(['src/a.go', 'src/b.go', 'src/c.go', 'tests/a.go']);
  });

  it('breaks tied ranks by path and handles duplicate or invalid ranks deterministically', () => {
    const files = ['c.go', 'b.go', 'a.go'].map(name => file(name));
    const ranks = [rank('c.go', NaN), rank('c.go', Infinity), rank('b.go', 4), rank('b.go', 1), rank('a.go', 1)];
    expect(paths(files, ranks)).toEqual(['a.go', 'b.go', 'c.go']);
    expect(paths(files, [...ranks].reverse())).toEqual(['a.go', 'b.go', 'c.go']);
  });

  it.each([
    'test/example.pb.go', 'vendor/example_pb2.py', 'service_pb2_grpc.py', 'service_pb.d.ts',
    'service.pb.cc', 'service.pbenum.dart', 'generated-proto/Message.java',
  ])('recognizes generated proto %s before other categories', name => {
    expect(paths([file(name), file('go.mod')])).toEqual(['go.mod', name]);
  });

  it('recognizes a protobuf compiler header, but not prose or a marker deep in source', () => {
    const generated = file('Message.java', '// Generated by the protocol buffer compiler. DO NOT EDIT!\nclass Message {}');
    const prose = file('README.md', '# Code generated by protoc');
    const source = file('Explain.java', 'String explanation = "Code generated by protoc";');
    const late = file('Late.java', '\n'.repeat(40) + '// Code generated by protoc');
    expect(paths([generated, file('go.mod'), prose, source, late]))
      .toEqual(['Explain.java', 'Late.java', 'README.md', 'go.mod', 'Message.java']);
  });

  it.each(['pom.xml', 'maven_install.json', 'go.sum', 'MODULE.bazel.lock', 'requirements-dev.txt', 'vendor/helper.go'])
  ('puts dependency %s below tests', name => {
    expect(paths([file(name), file('src/MainTest.java')])).toEqual(['src/MainTest.java', name]);
  });

  it.each(['tests/fixture.yaml', 'testdata/sample.go', 'ServiceTest.java', 'ServiceIT.java', 'TestDb.java', 'test_app.py', 'app.spec.ts'])
  ('recognizes test %s above dependencies and below YAML', name => {
    expect(paths([file('go.mod'), file(name), file('config.yml')])).toEqual(['config.yml', name, 'go.mod']);
  });

  it('keeps ordinary source and authored proto schemas in the source group', () => {
    const names = ['Audit.java', 'Contest.java', 'proto/schema.proto', 'BUILD.bazel'];
    const ranked = names.map((name, i) => rank(name, i));
    const files = names.map(name => file(name));
    files[0]!.diff_data = 'invalid JSON Code generated by protoc';
    expect(paths([file('a.yaml'), ...files], ranked)).toEqual([...names, 'a.yaml']);
  });
});
